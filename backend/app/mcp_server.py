
import json
from pathlib import Path

from mcp.server.fastmcp import FastMCP
from sqlalchemy import select

from .database import SessionLocal
from .models import DocumentShare
from .rag import retrieve


# --------------------------------------------------
# MCP server configuration
# --------------------------------------------------

mcp = FastMCP("advanced-rag-mcp")


# --------------------------------------------------
# Document retrieval with access control
# --------------------------------------------------

@mcp.tool()
def search_user_documents(
    question: str,
    trusted_user_id: int,
    limit: int = 5,
) -> list[dict]:
    """
    Search documents the specified user is authorized to access.

    The API backend supplies the authenticated user's ID.
    Shared document permissions are checked against PostgreSQL.
    """
    question = question.strip()

    if not question:
        return []

    if trusted_user_id <= 0:
        raise ValueError("A valid authenticated user ID is required.")

    safe_limit = max(1, min(int(limit), 20))

    # Retrieve explicit document-sharing permissions from PostgreSQL.
    db = SessionLocal()

    try:
        shared_document_ids = db.scalars(
            select(DocumentShare.document_id).where(
                DocumentShare.shared_with_user_id == trusted_user_id
            )
        ).all()

        # Fail closed if the permission lookup fails.
        # Do not search without verifying the sharing permissions.
    finally:
        db.close()

    # rag.retrieve applies the owner filter and the authorized
    # shared-document filter in ChromaDB.
    results = retrieve(
        query=question,
        owner_user_id=trusted_user_id,
        limit=safe_limit,
        shared_document_ids=list(shared_document_ids),
    )

    return [
        {
            "text": item["text"],
            "filename": item.get("metadata", {}).get(
                "filename", "document"
            ),
            "chunk_index": item.get("metadata", {}).get(
                "chunk_index"
            ),
            "document_id": item.get("metadata", {}).get(
                "document_id"
            ),
            "distance": item.get("distance"),
        }
        for item in results
    ]


# --------------------------------------------------
# Server monitoring report
# --------------------------------------------------

@mcp.tool()
def get_server_monitoring_report() -> dict:
    """
    Read the monitoring report generated by the monitoring service.

    The report is expected at:
    /run/advanced-rag-monitoring/agent_report.json
    """
    report_path = Path(
        "/run/advanced-rag-monitoring/agent_report.json"
    )

    if not report_path.is_file():
        return {
            "status": "unavailable",
            "message": "Monitoring report is not available.",
        }

    try:
        with report_path.open("r", encoding="utf-8") as report_file:
            report = json.load(report_file)

        if not isinstance(report, dict):
            return {
                "status": "error",
                "message": "Monitoring report must contain a JSON object.",
            }

        return report

    except json.JSONDecodeError:
        return {
            "status": "error",
            "message": "Monitoring report contains invalid JSON.",
        }

    except OSError:
        return {
            "status": "unavailable",
            "message": "Unable to read the monitoring report.",
        }


# --------------------------------------------------
# MCP entry point
# --------------------------------------------------

if __name__ == "__main__":
    mcp.run(transport="stdio")
